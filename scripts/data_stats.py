"""Describe the CUAD splits: contract counts, lengths and clause type frequencies.

Writes reports/data_stats.md. Token counts use the DeBERTa-v3 tokenizer (the fine-tuned
model) and the Qwen2.5 tokenizer (the local LLM), since both drive run time and cost.
"""

from collections import Counter
from pathlib import Path

import numpy as np
from transformers import AutoTokenizer

from clausescout.data.cuad import CATEGORIES, HIGH_STAKES, load_split

OUT = Path("reports/data_stats.md")
TOKENIZERS = {"DeBERTa-v3": "microsoft/deberta-v3-small", "Qwen2.5": "Qwen/Qwen2.5-7B-Instruct"}


def describe(values) -> str:
    v = np.asarray(values)
    q = np.percentile(v, [0, 25, 50, 75, 100])
    return " | ".join(f"{x:,.0f}" for x in [v.mean(), *q])


def main() -> None:
    splits = {name: load_split(name) for name in ["train", "val", "test"]}
    toks = {k: AutoTokenizer.from_pretrained(v) for k, v in TOKENIZERS.items()}
    lines = ["# CUAD data statistics", "", "Generated by `scripts/data_stats.py`.", ""]

    # Contract counts per split.
    lines += ["## Contracts per split", "", "| Split | Contracts |", "|---|---:|"]
    lines += [f"| {n} | {len(cs)} |" for n, cs in splits.items()]
    lines += [f"| total | {sum(len(c) for c in splits.values())} |", ""]

    # Length statistics in words and tokens.
    lines += [
        "## Contract length",
        "",
        "| Split | Unit | Mean | Min | 25% | Median | 75% | Max |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    totals = {}
    for n, cs in splits.items():
        words = [len(c.text.split()) for c in cs]
        lines.append(f"| {n} | words | {describe(words)} |")
        for tname, tok in toks.items():
            # I tokenise without special tokens so the count is just the contract.
            counts = [len(tok(c.text, add_special_tokens=False)["input_ids"]) for c in cs]
            totals[(n, tname)] = sum(counts)
            lines.append(f"| {n} | {tname} tokens | {describe(counts)} |")
    lines += [
        "",
        "Total tokens per split: " + ", ".join(f"{n} {t} {v:,}" for (n, t), v in totals.items()),
        "",
    ]

    # How often each clause type appears, by contract and by span.
    contract_counts = {
        n: Counter(cat for c in cs for cat in c.present()) for n, cs in splits.items()
    }
    span_counts = {
        n: Counter({cat: sum(len(c.labels[cat]) for c in cs) for cat in CATEGORIES})
        for n, cs in splits.items()
    }
    lines += [
        "## Clause type frequency",
        "",
        "Contracts containing the type (spans in brackets). High-stakes types are in bold.",
        "",
        "| Clause type | train | val | test | all contracts |",
        "|---|---:|---:|---:|---:|",
    ]
    everywhere = Counter()
    for n in splits:
        everywhere.update(contract_counts[n])
    for cat in sorted(CATEGORIES, key=lambda c: -everywhere[c]):
        name = f"**{cat}**" if cat in HIGH_STAKES else cat
        cells = [f"{contract_counts[n][cat]} ({span_counts[n][cat]})" for n in splits]
        lines.append(f"| {name} | {' | '.join(cells)} | {everywhere[cat]} |")

    rarest = sorted(CATEGORIES, key=lambda c: everywhere[c])[:5]
    lines += ["", "## Five rarest types (by contracts containing them, all splits)", ""]
    lines += [
        f"{i}. {c}: {everywhere[c]} contracts (train {contract_counts['train'][c]}, "
        f"val {contract_counts['val'][c]}, test {contract_counts['test'][c]})"
        for i, c in enumerate(rarest, 1)
    ]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
