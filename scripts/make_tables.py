"""Build markdown tables from saved experiment results, so report numbers come from real runs.

Usage: python scripts/make_tables.py --split val --out reports/validation_tables.md
"""

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(x, pct=False, digits=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{x:.1%}" if pct else f"{x:.{digits}f}"


def with_ci(value, ci, key):
    # I show the 95% interval next to a number when the run bootstrapped one.
    if ci and key in ci:
        lo, hi = ci[key]
        return f"{fmt(value)} ({fmt(lo)}-{fmt(hi)})"
    return fmt(value)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="val")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--only", nargs="*", help="experiment names to include, in this order")
    args = ap.parse_args()

    results = [json.loads(p.read_text(encoding="utf-8"))
               for p in sorted((ROOT / "experiments" / "results").glob("*.json"))]
    results = [r for r in results if r["split"] == args.split]
    if args.only:
        order = {n: i for i, n in enumerate(args.only)}
        results = sorted([r for r in results if r["name"] in order], key=lambda r: order[r["name"]])

    lines = [f"# Tables for the {args.split} split", "",
             "Generated by `scripts/make_tables.py` from `experiments/results/`.", ""]

    lines += ["## Span level (CUAD protocol)", "",
              "| Method | AUPR | Precision at 80% recall | Precision at 90% recall | Macro AUPR |",
              "|---|---:|---:|---:|---:|"]
    for r in results:
        s = r["span"]["overall"]
        lines.append(f"| {r['name']} | {with_ci(s['aupr'], s.get('ci'), 'aupr')} | "
                     f"{with_ci(s['prec_at_80'], s.get('ci'), 'prec_at_80')} | "
                     f"{with_ci(s['prec_at_90'], s.get('ci'), 'prec_at_90')} | "
                     f"{fmt(r['span']['macro_aupr'])} |")

    lines += ["", "## Contract level (is the clause there, and did we quote it)", "",
              "Micro scores pool every (contract, clause type) pair. High-stakes columns average "
              "the eight high-stakes types. Found = clause present and a correct span quoted.", "",
              "| Method | Threshold | Precision | Recall | F1 | Macro F1 | High-stakes recall "
              "| High-stakes F2 | High-stakes found |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in results:
        m, h = r["contract"]["micro"], r["contract"]["high_stakes"]
        p, rc, f1 = (with_ci(m[k], m.get("ci"), k) for k in ("precision", "recall", "f1"))
        lines.append(f"| {r['name']} | {r['threshold']} | {p} | {rc} | {f1} | "
                     f"{fmt(r['contract']['macro']['f1'])} | {fmt(h['recall'])} | {fmt(h['f2'])} | "
                     f"{fmt(h['found_recall'])} |")

    if results:
        lines += ["", "## High-stakes clause types", "",
                  "Span AUPR / contract recall / found with a correct span, per method.", "",
                  "| Clause type | " + " | ".join(r["name"] for r in results) + " |",
                  "|---|" + "---:|" * len(results)]
        for cat in results[0]["high_stakes_types"]:
            cells = []
            for r in results:
                pc = r["per_category"][cat]
                cells.append(f"{fmt(pc['span']['aupr'], digits=2)} / "
                             f"{fmt(pc['contract']['recall'], digits=2)} / "
                             f"{fmt(pc['contract']['found_recall'], digits=2)}")
            lines.append(f"| {cat} | " + " | ".join(cells) + " |")

    lines += ["", "## Grounding, time and cost", "",
              "| Method | Spans returned | Rejected as not verbatim | Rejection rate "
              "| Seconds per contract | Cost per contract (USD) | Hardware |",
              "|---|---:|---:|---:|---:|---:|---|"]
    for r in results:
        g, hw = r["grounding"], r["hardware"]
        where = hw.get("gpu") or hw.get("cpu") or "?"
        lines.append(f"| {r['name']} | {g['submitted']:,} | {g['rejected']:,} | "
                     f"{fmt(g['rejection_rate'], pct=True)} | {r['time']['per_contract_s']:.1f} | "
                     f"{r['cost_per_contract_usd']:.4f} | {where} |")

    text = "\n".join(lines) + "\n"
    if args.out:
        args.out.write_text(text, encoding="utf-8")
        print(f"Wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
